import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { parseNitCap, parseReviewMd, parseSkipItem } from "./review-md.ts";
import { applySkips, globToRegExp, matchesGlob } from "./skip.ts";
import { parseDiff } from "./diff.ts";

const fixture = (name: string) => readFileSync(new URL(`./fixtures/${name}`, import.meta.url), "utf8");

test("cass-operator REVIEW.md: skip entries and nit cap", () => {
  const r = parseReviewMd(fixture("cass-operator-REVIEW.md"));
  assert.deepEqual(r.found, { skipPaths: true, limits: true });
  assert.equal(r.nitCap, 3);
  assert.deepEqual(
    r.skipEntries.map((e) => [e.glob, e.qualifier]),
    [
      ["**/zz_generated.deepcopy.go", undefined],
      ["config/crd/bases/**", undefined],
      ["go.sum", undefined],
      ["tests/testdata/**", "unless the PR's purpose is test data"],
    ],
  );
  assert.deepEqual(r.unparsedSkipItems, []);
});

test("template REVIEW.md: placeholder cap in angle brackets, plain globs", () => {
  const r = parseReviewMd(fixture("template-REVIEW.md"));
  assert.equal(r.nitCap, 3);
  assert.deepEqual(
    r.skipEntries.map((e) => e.glob),
    ["generated/**", "vendor/**", "**/fixtures/**"],
  );
});

test("empty REVIEW.md: no skips, no cap", () => {
  for (const text of ["", "\n\n", "# Review guidance\n\nNothing here.\n"]) {
    const r = parseReviewMd(text);
    assert.deepEqual(r.skipEntries, []);
    assert.equal(r.nitCap, undefined);
    assert.deepEqual(r.found, { skipPaths: false, limits: false });
  }
});

test("missing Limits heading means no cap even if the text mentions nits elsewhere", () => {
  const r = parseReviewMd("## Focus on\n- At most 2 nits please\n## Skip these paths\n- `a/**`\n");
  assert.equal(r.nitCap, undefined);
  assert.equal(r.found.limits, false);
});

test("CRLF, heading variants, nested subsections, fences and comments", () => {
  const text = [
    "# Review",
    "### Skip These Paths: ###",
    "<!-- - `commented/**` -->",
    "- `gen/**`",
    "  continued text, unless the PR is about codegen",
    "#### Notes",
    "* `vendor/**`",
    "```",
    "## Limits",
    "- At most 9 nits",
    "```",
    "## LIMITS",
    "- No more than **two** nits per review.",
    "",
  ].join("\r\n");
  const r = parseReviewMd(text);
  assert.deepEqual(
    r.skipEntries.map((e) => [e.glob, e.qualifier]),
    [
      ["gen/**", "continued text, unless the PR is about codegen"],
      ["vendor/**", undefined],
    ],
  );
  assert.equal(r.nitCap, undefined, "bold number word is not a plain number");
  assert.equal(parseNitCap(["- No more than two nits per review."]), 2);
});

test("skip item forms", () => {
  assert.deepEqual(
    parseSkipItem("`a/**`, `b/*.go`").map((e) => [e.glob, e.qualifier]),
    [
      ["a/**", undefined],
      ["b/*.go", undefined],
    ],
  );
  assert.deepEqual(parseSkipItem("vendor/** (third-party)").map((e) => e.qualifier), ["(third-party)"]);
  assert.deepEqual(parseSkipItem("anything generated by the tool"), []);
  assert.deepEqual(parseSkipItem("`dist/`").map((e) => e.glob), ["dist/"]);
});

test("nit cap forms", () => {
  assert.equal(parseNitCap(["- At most 3 Nits per review."]), 3);
  assert.equal(parseNitCap(["- At most <3> nits per review."]), 3);
  assert.equal(parseNitCap(["- Max 0 nits."]), 0);
  assert.equal(parseNitCap(["- At most one nit."]), 1);
  assert.equal(parseNitCap(["- Tag each finding."]), undefined);
  assert.equal(parseNitCap(["- At most 99999999999999999999 nits"]), undefined);
});

test("glob dialect", () => {
  assert.ok(matchesGlob("zz_generated.deepcopy.go", "**/zz_generated.deepcopy.go"));
  assert.ok(matchesGlob("api/v1/zz_generated.deepcopy.go", "**/zz_generated.deepcopy.go"));
  assert.ok(!matchesGlob("api/v1/zz_generated.deepcopy.go.orig", "**/zz_generated.deepcopy.go"));
  assert.ok(matchesGlob("config/crd/bases/x.yaml", "config/crd/bases/**"));
  assert.ok(!matchesGlob("other/config/crd/bases/x.yaml", "config/crd/bases/**"));
  assert.ok(matchesGlob("go.sum", "go.sum"));
  assert.ok(matchesGlob("tools/go.sum", "go.sum"), "slash-less pattern matches at any depth");
  assert.ok(!matchesGlob("tools/go.sum", "/go.sum"), "leading slash anchors");
  assert.ok(matchesGlob("a/b.pb.go", "*.pb.go"));
  assert.ok(!matchesGlob("a/b.go", "a/*.pb.go"));
  assert.ok(!matchesGlob("a/x/b.go", "a/*.go"), "* stays within a segment");
  assert.ok(matchesGlob("a/x/b.go", "a/**/*.go"));
  assert.ok(matchesGlob("a/b.go", "a/**/*.go"), "** matches zero segments");
  assert.ok(matchesGlob("dist/x/y", "dist/"));
  assert.ok(matchesGlob("a/b.yaml", "a/*.{yaml,yml}"));
  assert.ok(matchesGlob("a/v1.go", "a/v[0-9].go"));
  assert.ok(!matchesGlob("a/vx.go", "a/v[0-9].go"));
  assert.ok(matchesGlob("a+b(c).go", "a+b(c).go"), "regex metacharacters are literal");
  assert.ok(globToRegExp("[").test("["), "unterminated class is literal");
});

test("applySkips: binary always, hard globs, qualified entries left to the reviewer, renames and deletes", () => {
  const diff = (path: string, extra = "") =>
    `diff --git a/${path} b/${path}\n${extra}--- a/${path}\n+++ b/${path}\n@@ -1 +1 @@\n-a\n+b\n`;
  const files = parseDiff(
    diff("main.go") +
      diff("api/v1/zz_generated.deepcopy.go") +
      diff("tests/testdata/x.json") +
      "diff --git a/img.png b/img.png\nBinary files a/img.png and b/img.png differ\n" +
      "diff --git a/config/crd/bases/old.yaml b/config/new.yaml\nsimilarity index 90%\nrename from config/crd/bases/old.yaml\nrename to config/new.yaml\n" +
      "diff --git a/go.sum b/go.sum\ndeleted file mode 100644\n--- a/go.sum\n+++ /dev/null\n@@ -1 +0,0 @@\n-x\n",
  );
  const { skipEntries } = parseReviewMd(fixture("cass-operator-REVIEW.md"));
  const r = applySkips(files, skipEntries);
  assert.deepEqual(
    r.included.map((f) => f.path),
    ["main.go", "tests/testdata/x.json"],
  );
  assert.deepEqual(r.excluded, [
    { path: "api/v1/zz_generated.deepcopy.go", reason: 'REVIEW.md "Skip these paths": **/zz_generated.deepcopy.go' },
    { path: "img.png", reason: "binary file" },
    { path: "config/new.yaml", reason: 'REVIEW.md "Skip these paths": config/crd/bases/**' },
    { path: "go.sum", reason: 'REVIEW.md "Skip these paths": go.sum' },
  ]);
  assert.deepEqual(r.softSkips, [
    { path: "tests/testdata/x.json", glob: "tests/testdata/**", qualifier: "unless the PR's purpose is test data" },
  ]);
});
